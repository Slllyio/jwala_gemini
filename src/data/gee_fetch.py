# ── Main V3 training-chip pipeline (per beat) ─────────────────────────────────

def export_training_chips(beats: list, cfg: dict, test_mode: bool):
    """
    V3 pipeline: exports training chips beat-by-beat across Guna Division.

    For each beat x year:
      1. Get forest-loss positive polygons (Hansen) within the beat boundary
      2. Sample extra positives via LULC change (agri expansion)
      3. For each positive: S1-pinpoint cut month -> anchor date -> 18-band chip
      4. Sample equal negatives from intact forest areas
      5. Export chip image + label to Google Drive (or local in test mode)

    Estimated output: ~800-1200 chips (vs 275 current) covering 2144 sq km
    """
    scale      = cfg["gee"]["tile_scale"]
    cloud_thr  = cfg["gee"]["cloud_threshold"]
    start_year = int(cfg["gee"]["date_range"][0][:4])
    end_year   = int(cfg["gee"]["date_range"][1][:4])
    chip_dir   = cfg["paths"].get("chip_dir", "data/chips")
    folder     = "prithvi_guna_v3"

    Path(chip_dir).mkdir(parents=True, exist_ok=True)

    log.info(f"\nV3 Training chip export: {len(beats)} beats x {end_year-max(start_year,2019)+1} years")
    log.info(f"  Folder: {folder}")
    log.info(f"  Chip dir: {chip_dir}")
    log.info(f"  Test mode: {test_mode}")

    chip_id    = 0
    task_count = 0

    for beat_info in beats:
        beat_aoi  = beat_info["geometry"]
        beat_name = f"{beat_info['range']}_{beat_info['beat']}".replace(" ", "_")
        log.info(f"\n  Beat: {beat_name} (~{beat_info['area_sqkm']:.1f} sq km)")

        for year in range(max(start_year, 2019), end_year + 1):

            # === POSITIVE CHIPS: Hansen forest loss (Triple-Lock) ===
            loss_mask = get_hansen_loss_mask(beat_aoi, year)
            pos_vectors_raw = (loss_mask.selfMask()
                               .reduceToVectors(
                                   geometry=beat_aoi, scale=30,
                                   geometryType="polygon",
                                   maxPixels=1e8)
                               .limit(200))  # cap pre-filter; will reduce after area check

            # 0.20 ha minimum area filter -- sub-pixel Hansen noise elimination.
            # Hansen 30m: 1 pixel = 0.09 ha. Anything <0.20 ha is likely a
            # cloud-shadow artifact or BRDF edge, not a real felling event.
            # A logger clearing even a single row of trees leaves ≥0.20 ha.
            min_area_m2 = _HANSEN_MIN_HA * 10_000  # 0.20 ha = 2000 sq m
            pos_vectors = pos_vectors_raw.map(
                lambda f: f.set("area_m2", f.geometry().area(maxError=1))
            ).filter(ee.Filter.gte("area_m2", min_area_m2)).limit(100)

            try:
                pos_count = pos_vectors.size().getInfo()
            except Exception:
                pos_count = 0

            log.info(f"    {year}: {pos_count} positive polygons (≥{_HANSEN_MIN_HA:.2f} ha)")

            if pos_count > 0:
                features = pos_vectors.toList(pos_vectors.size()).getInfo()

                s1_rejected = 0
                for feat in features:
                    geom      = ee.Geometry(feat["geometry"])
                    centroid  = geom.centroid(maxError=10)
                    chip_geom = centroid.buffer(1120).bounds()

                    # MANDATORY S1 radar gate: reject if no structural VH drop confirmed.
                    # This is the primary defense against Hansen leaf-drop false positives.
                    # At treecover2000 >= 5%, Hansen casts a wide spatial net intentionally;
                    # S1 confirmation is what makes those detections trustworthy.
                    anchor_date = find_s1_cut_month(geom, year)
                    if anchor_date is None:
                        s1_rejected += 1
                        continue  # discard -- phenological noise, not real felling

                    stack = make_three_frame_stack(chip_geom, anchor_date, cloud_thr)
                    label = loss_mask.clip(chip_geom)

                    prefix = f"chip_pos_{beat_name}_{year}_{chip_id:05d}"
                    all_bands = [f"{b}_{i}" for i in range(3) for b in _PRITHVI_BANDS]

                    if test_mode:
                        export_local(stack, f"{chip_dir}/{prefix}_img.tif",
                                     chip_geom, scale=10, bands=all_bands)
                        export_local(label, f"{chip_dir}/{prefix}_lbl.tif",
                                     chip_geom, scale=10, bands=["forest_loss"])
                    else:
                        export_to_drive(stack, f"{prefix}_img", chip_geom, 10, folder)
                        export_to_drive(label, f"{prefix}_lbl", chip_geom, 10, folder)

                    chip_id    += 1
                    task_count += 1

                if s1_rejected:
                    log.info(f"      ↳ S1-rejected (leaf-drop FP): {s1_rejected}/{pos_count}")

            # ============================================================
            # NEGATIVE CHIPS -- 3-tier sampling strategy
            #   50% intact forest, post-monsoon anchor (standard)
            #   25% intact forest, summer anchor   (phenological)
            #   25% rocky/barren/riverbed           (spatial hard negatives)
            # The 3rd tier is critical: after leaf-drop, bare rock looks
            # identical to cleared forest in NIR/SWIR composites.
            # ============================================================
            n_total = max(pos_count * 2, 4)
            n_hard  = max(n_total // 4, 1)   # 25% hard negatives
            n_soft  = n_total - n_hard        # 75% standard / phenological

            intact_mask = loss_mask.eq(0)

            # -- Soft negatives: intact forest --------------------------------
            neg_points = (intact_mask.selfMask()
                          .addBands(ee.Image.pixelLonLat())
                          .sample(region=beat_aoi, scale=120,
                                  numPixels=n_soft, seed=year * 100 + chip_id,
                                  geometries=True))
            try:
                neg_features = neg_points.toList(neg_points.size()).getInfo()
            except Exception:
                neg_features = []

            for i, feat in enumerate(neg_features):
                centroid  = ee.Geometry.Point(feat["geometry"]["coordinates"])
                chip_geom = centroid.buffer(1120).bounds()

                # 1-in-3: summer anchor (phenological hard negative)
                if i % 3 == 0:
                    m           = [4, 5, 6][i % 3]
                    anchor_date = f"{year}-{m:02d}-15"
                    neg_type    = "summer"
                else:
                    anchor_date = f"{year}-09-15"   # post-monsoon full canopy
                    neg_type    = "postmonsoon"

                stack = make_three_frame_stack(chip_geom, anchor_date, cloud_thr)
                label = loss_mask.clip(chip_geom)   # all zeros

                prefix    = f"chip_neg_{neg_type}_{beat_name}_{year}_{chip_id:05d}"
                all_bands = [f"{b}_{i}" for i in range(3) for b in _PRITHVI_BANDS]

                if test_mode:
                    export_local(stack, f"{chip_dir}/{prefix}_img.tif",
                                 chip_geom, scale=10, bands=all_bands)
                else:
                    export_to_drive(stack, f"{prefix}_img", chip_geom, 10, folder)
                    export_to_drive(label, f"{prefix}_lbl", chip_geom, 10, folder)

                chip_id    += 1
                task_count += 1

            # -- Hard negatives: rocky / barren / sandy riverbeds -------------
            hard_neg_mask = get_hard_negative_mask(beat_aoi, year)
            hard_points   = (hard_neg_mask.selfMask()
                             .addBands(ee.Image.pixelLonLat())
                             .sample(region=beat_aoi, scale=120,
                                     numPixels=n_hard, seed=year * 200 + chip_id,
                                     geometries=True))
            try:
                hard_features = hard_points.toList(hard_points.size()).getInfo()
                n_hard_found  = len(hard_features)
            except Exception:
                hard_features = []
                n_hard_found  = 0

            if n_hard_found > 0:
                log.info(f"      {n_hard_found} hard-negative chips (rocky/barren/riverbed)")

            for feat in hard_features:
                centroid  = ee.Geometry.Point(feat["geometry"]["coordinates"])
                chip_geom = centroid.buffer(1120).bounds()
                # Always use Oct anchor: peak dry season, worst-case spectral confusion
                anchor_date = f"{year}-10-15"
                stack = make_three_frame_stack(chip_geom, anchor_date, cloud_thr)
                label = loss_mask.clip(chip_geom)   # all zeros

                prefix    = f"chip_neg_hardrock_{beat_name}_{year}_{chip_id:05d}"
                all_bands = [f"{b}_{i}" for i in range(3) for b in _PRITHVI_BANDS]

                if test_mode:
                    export_local(stack, f"{chip_dir}/{prefix}_img.tif",
                                 chip_geom, scale=10, bands=all_bands)
                else:
                    export_to_drive(stack, f"{prefix}_img", chip_geom, 10, folder)
                    export_to_drive(label, f"{prefix}_lbl", chip_geom, 10, folder)

                chip_id    += 1
                task_count += 1

    log.info(f"\nDone. {task_count} GEE export tasks submitted ({chip_id} chips).")
    if not test_mode:
        log.info("Monitor: https://code.earthengine.google.com/tasks")
        log.info(f"Download chips from Drive folder: {folder}/")
        log.info(f"Then preprocess: python src/data/preprocess.py --chip-dir data/chips")


