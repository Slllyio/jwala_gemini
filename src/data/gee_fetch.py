# ── Band registry ─────────────────────────────────────────────────────────────
_HLS_L30_BANDS  = ["B2",  "B3",  "B4",  "B5",   "B6",  "B7"]   # Landsat 8/9
_HLS_S30_BANDS  = ["B2",  "B3",  "B4",  "B8A",  "B11", "B12"]  # Sentinel-2
_PRITHVI_BANDS  = ["Blue","Green","Red", "NIR",  "SWIR1","SWIR2"]

# Sentinel-1 parameters for cut-date pinpointing
_S1_COLLECTION  = "COPERNICUS/S1_GRD"
_S1_VH_DROP_DB  = 2.0               # dB drop threshold: >2dB = structural canopy loss
_S1_MODE        = "IW"

# Hansen GFC calibration for Guna, Madhya Pradesh (Dry Deciduous Forest)
#
# Canopy threshold set to 5% (not 10%) because Hansen's algorithm was calibrated
# on dense tropical canopy (Amazon/Congo). In MP's open dry-deciduous forest
# (Teak, Sal, Palash at 40-60% cover), even 10% misses the majority of selective
# logging events that FSI ground surveys detect.
#
# The increased noise from 5% is purged by the MANDATORY S1 radar gate:
#   - Radar (C-band VH backscatter) is structurally sensitive — it only drops
#     when woody biomass is physically removed. Leaf-drop does NOT change radar.
#   - Any Hansen polygon that fails the S1 2dB structural test is NOT labelled
#     as a positive — it is DISCARDED entirely (find_s1_cut_month returns None).
#
# Result: a wider spatial net (5%) + harder confirmation gate (mandatory S1)
# produces more true positives with no increase in false positives.
_HANSEN_CANOPY_THR = 5    # treecover2000 minimum % — wide net; S1 is the real filter
_HANSEN_MIN_YEAR   = 15   # lossyear >= 15 (2015) -- start of Sentinel-1 era
_HANSEN_MAX_YEAR   = 24   # lossyear <= 24 (2024)
_HANSEN_MIN_HA     = 0.20 # minimum polygon area in hectares -- below this is sub-pixel noise

# ESRI LULC class IDs
_LULC_TREES     = 2
_LULC_GRASS     = 3
_LULC_FLOODED   = 4
_LULC_SCRUB     = 6
_LULC_RANGELAND = 11
_LULC_CROPS     = 5
_LULC_BARREN    = 7    # bare rock/sand -- hard negative source
_LULC_WATER     = 1    # rivers/waterbodies
_LULC_LAST_YEAR = 2023
_NON_CROP       = [_LULC_TREES, _LULC_GRASS, _LULC_FLOODED, _LULC_SCRUB, _LULC_RANGELAND]
# Hard negative LULC classes: persistently non-forest, visually similar after leaf-drop
_HARD_NEG_LULC  = [_LULC_BARREN, _LULC_WATER]   # rocky outcrops, sandy riverbeds

